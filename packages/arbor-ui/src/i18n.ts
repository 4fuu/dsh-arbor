/** One translate function, as `ctx.locale.bind` answers it. */
export type Translate = (key: string, args?: Record<string, string | number>) => string

/** Replace `{name}` placeholders in one string. */
export function format(template: string, args?: Record<string, string | number>): string {
  if (args === undefined) return template
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (
    Object.hasOwn(args, name) ? String(args[name]) : whole
  ))
}

/** The fallback translate function, for a reduced client graph with no locale service. */
export function fallbackTranslate(key: string, args?: Record<string, string | number>): string {
  const value = (zh as Record<string, string>)[key]
  return value === undefined ? key : format(value, args)
}


